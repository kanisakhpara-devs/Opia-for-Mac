LUT_N = 33
_cache, _lock = {}, threading.Lock()
D50 = np.array([0.9642, 1.0, 0.8249])
SPACES = {   # name: (primaries xy, white xy, gamma or 'srgb')
    'AdobeRGB': ('Adobe RGB (1998) compatible', ((0.64, 0.33), (0.21, 0.71), (0.15, 0.06)), (0.3127, 0.3290), 2.19921875),
    'DisplayP3': ('Display P3', ((0.680, 0.320), (0.265, 0.690), (0.150, 0.060)), (0.3127, 0.3290), 'srgb'),
    'ProPhoto': ('ProPhoto RGB compatible', ((0.7347, 0.2653), (0.1596, 0.8404), (0.0366, 0.0001)), (0.3457, 0.3585), 1.8),
}


def _xyz(x, y):
    return np.array([x / y, 1.0, (1 - x - y) / y])


def _bradford(src, dst):
    M = np.array([[0.8951, 0.2664, -0.1614], [-0.7502, 1.7135, 0.0367], [0.0389, -0.0685, 1.0296]])
    s, d = M @ src, M @ dst
    return np.linalg.inv(M) @ np.diag(d / s) @ M


def _s15(v):
    return struct.pack('>i', int(round(v * 65536)))


def make_matrix_profile(desc, prim, white, gamma):
    """Write a minimal ICC v2 matrix/TRC display profile."""
    W = _xyz(*white)
    M = np.column_stack([_xyz(*p) for p in prim])
    M = M * np.linalg.solve(M, W)
    M = _bradford(W, D50) @ M

    def xyz_tag(v):
        return b'XYZ \0\0\0\0' + b''.join(_s15(c) for c in v)
    d = desc.encode('ascii') + b'\0'
    desc_tag = b'desc\0\0\0\0' + struct.pack('>I', len(d)) + d + b'\0' * (4 + 4 + 2 + 1 + 67)
    cprt = b'text\0\0\0\0' + b'Generated by Opia. No copyright, use freely.\0'
    if gamma == 'srgb':
        xs = np.linspace(0, 1, 1024)
        ys = np.where(xs <= 0.04045, xs / 12.92, ((xs + 0.055) / 1.055) ** 2.4)
        trc = b'curv\0\0\0\0' + struct.pack('>I', 1024) + b''.join(struct.pack('>H', int(round(y * 65535))) for y in ys)
    else:
        trc = b'curv\0\0\0\0' + struct.pack('>I', 1) + struct.pack('>H', int(round(gamma * 256)))
    tags = [(b'desc', desc_tag), (b'cprt', cprt), (b'wtpt', xyz_tag(W)), (b'rXYZ', xyz_tag(M[:, 0])),
            (b'gXYZ', xyz_tag(M[:, 1])), (b'bXYZ', xyz_tag(M[:, 2])), (b'rTRC', trc), (b'gTRC', trc), (b'bTRC', trc)]
    offset = 128 + 4 + 12 * len(tags)
    table, data, placed = b'', b'', {}
    for sig, blob in tags:
        if blob in placed:
            off = placed[blob]
        else:
            off = offset + len(data)
            placed[blob] = off
            data += blob + b'\0' * (-len(blob) % 4)
        table += sig + struct.pack('>II', off, len(blob))
    now = datetime.datetime(2024, 1, 1)
    head = (struct.pack('>I', offset + len(data)) + b'lcms' + struct.pack('>I', 0x02100000) + b'mntrRGB XYZ '
            + struct.pack('>6H', now.year, now.month, now.day, 0, 0, 0) + b'acspMSFT' + b'\0' * 4 + b'\0' * 8 + b'\0' * 8
            + struct.pack('>I', 0) + b''.join(_s15(c) for c in D50) + b'lmra' + b'\0' * 44)
    return head + struct.pack('>I', len(tags)) + table + data


def profile_dirs():
    dirs = [os.path.join(core.HOME, 'Profiles')]
    if sys.platform == 'darwin':
        dirs += [os.path.expanduser('~/Library/ColorSync/Profiles'), '/Library/ColorSync/Profiles', '/System/Library/ColorSync/Profiles']
    elif sys.platform == 'win32':
        dirs.append(os.path.join(os.environ.get('SystemRoot', r'C:\Windows'), 'System32', 'spool', 'drivers', 'color'))
    return dirs


@api
def profiles():
    out = [{'id': 'sRGB', 'name': 'sRGB IEC61966-2.1', 'space': 'RGB', 'builtin': True}]
    out += [{'id': k, 'name': v[0], 'space': 'RGB', 'builtin': True} for k, v in SPACES.items()]
    for d in profile_dirs():
        if not os.path.isdir(d):
            continue
        for f in sorted(os.listdir(d)):
            if not f.lower().endswith(('.icc', '.icm')):
                continue
            p = os.path.join(d, f)
            try:
                prof = ImageCms.getOpenProfile(p)
                space = prof.profile.xcolor_space.strip()
                name = (ImageCms.getProfileDescription(prof) or f).strip() or f
            except (ImageCms.PyCMSError, OSError):
                continue
            if space in ('RGB', 'CMYK', 'GRAY'):
                out.append({'id': p, 'name': name, 'space': space, 'builtin': False, 'file': f})
    return out


@api
def profile_add(path):
    """Copy a user-chosen .icc/.icm into the app's profile folder."""
    if not path.lower().endswith(('.icc', '.icm')):
        raise ApiError('Choose an .icc or .icm file')
    try:
        ImageCms.getOpenProfile(path)
    except (ImageCms.PyCMSError, OSError):
        raise ApiError('That file is not a readable ICC profile')
    d = os.path.join(core.HOME, 'Profiles')
    os.makedirs(d, exist_ok=True)
    target = os.path.join(d, os.path.basename(path))
    shutil.copy2(path, target)
    return profiles()


def profile_bytes(pid):
    if pid in (None, '', 'sRGB'):
        return ImageCms.ImageCmsProfile(ImageCms.createProfile('sRGB')).tobytes()
    if pid in SPACES:
        return make_matrix_profile(*SPACES[pid])
    with open(pid, 'rb') as f:
        return f.read()


def get_profile(pid):
    return ImageCms.ImageCmsProfile(io.BytesIO(profile_bytes(pid)))


def space_of(prof):
    return prof.profile.xcolor_space.strip()


INTENTS = {'perceptual': ImageCms.Intent.PERCEPTUAL, 'relative': ImageCms.Intent.RELATIVE_COLORIMETRIC,
           'saturation': ImageCms.Intent.SATURATION, 'absolute': ImageCms.Intent.ABSOLUTE_COLORIMETRIC}


def convert(im, pid, intent='relative'):
    """sRGB PIL image -> image in the target profile's space (RGB or CMYK) plus the bytes to embed."""
    data = profile_bytes(pid)
    if pid in (None, '', 'sRGB'):
        return im, data
    prof = ImageCms.ImageCmsProfile(io.BytesIO(data))
    mode = {'RGB': 'RGB', 'CMYK': 'CMYK', 'GRAY': 'L'}[space_of(prof)]
    out = ImageCms.profileToProfile(im, get_profile('sRGB'), prof, renderingIntent=INTENTS.get(intent, 1), outputMode=mode,
                                    flags=ImageCms.Flags.BLACKPOINTCOMPENSATION)
    return out, data


def proof_lut(pid, intent='perceptual', paper=False):
    """RGBA 33^3 table: rgb = how sRGB colours will look through the profile, a = 255 where out of gamut."""
    key = (pid, intent, bool(paper))
    with _lock:
        if key in _cache:
            return _cache[key]
    srgb, prof = get_profile('sRGB'), get_profile(pid)
    mode = {'RGB': 'RGB', 'CMYK': 'CMYK', 'GRAY': 'L'}[space_of(prof)]
    g = np.linspace(0, 255, LUT_N).round().astype(np.uint8)
    b, gg, r = np.meshgrid(g, g, g, indexing='ij')
    grid = np.stack([r, gg, b], -1).reshape(LUT_N * LUT_N, LUT_N, 3)
    im = Image.fromarray(np.ascontiguousarray(grid), 'RGB')
    BPC = ImageCms.Flags.BLACKPOINTCOMPENSATION
    rel = ImageCms.Intent.RELATIVE_COLORIMETRIC
    # To the device with the chosen intent, then back to the screen: relative + black point compensation normally,
    # absolute colorimetric when simulating paper white and ink black.
    to_dev = ImageCms.buildTransform(srgb, prof, 'RGB', mode, renderingIntent=INTENTS.get(intent, 0), flags=BPC)
    if paper:
        to_screen = ImageCms.buildTransform(prof, srgb, mode, 'RGB', renderingIntent=ImageCms.Intent.ABSOLUTE_COLORIMETRIC)
    else:
        to_screen = ImageCms.buildTransform(prof, srgb, mode, 'RGB', renderingIntent=rel, flags=BPC)
    seen = np.asarray(ImageCms.applyTransform(ImageCms.applyTransform(im, to_dev), to_screen).convert('RGB'))
    # Gamut warning: colours that cannot survive a colorimetric round trip lose chroma. Compare a*b* only,
    # so the small lightness errors every printer profile has do not light up the whole picture.
    fwd = ImageCms.buildTransform(srgb, prof, 'RGB', mode, renderingIntent=rel, flags=BPC)
    back = ImageCms.buildTransform(prof, srgb, mode, 'RGB', renderingIntent=rel, flags=BPC)
    trip = ImageCms.applyTransform(ImageCms.applyTransform(im, fwd), back).convert('RGB')
    to_lab = ImageCms.buildTransform(srgb, ImageCms.createProfile('LAB'), 'RGB', 'LAB')
    la = np.asarray(ImageCms.applyTransform(im, to_lab)).view(np.int8)[..., 1:].astype(np.float32)
    lb = np.asarray(ImageCms.applyTransform(trip, to_lab)).view(np.int8)[..., 1:].astype(np.float32)
    oog = (np.hypot(la[..., 0] - lb[..., 0], la[..., 1] - lb[..., 1]) > 9).astype(np.uint8) * 255
    out = np.dstack([seen, oog]).tobytes()
    with _lock:
        _cache[key] = out
    return out


@img
def lut(rest, q):
    return Binary(proof_lut(q.get('profile', 'sRGB'), q.get('intent', 'perceptual'), q.get('paper') == '1'),
                  'application/octet-stream')
